/**
 * Internal helper: debit the user's wallet and create a transaction record.
 * Applies the 10% random failure rate.
 */
async function processTransaction(
  userId: string,
  service: TransactionService,
  serviceCode: string,
  amount: number,
  extra: Partial<Transaction>,
): Promise<Transaction> {
  const wallet = db.wallets.find((w) => w.userId === userId)
  if (!wallet) return delayedError('Wallet not found.')

  if (wallet.balance < amount) {
    return delayedError(`Insufficient balance. You need ₦${amount.toLocaleString()} but have ₦${wallet.balance.toLocaleString()}.`)
  }

  // Determine outcome (10% failure rate)
  let status: TransactionStatus = 'Success'
  if (shouldFail()) {
    status = 'Failed'
  }

  // Only debit on success
  if (status === 'Success') {
    wallet.balance -= amount
  }

  const txn: Transaction = {
    id: uid('txn'),
    userId,
    reference: txnRef(serviceCode),
    type: 'Debit',
    service,
    amount,
    status,
    aggregatorUsed: Math.random() > 0.5 ? 'Toppa' : 'VTpass',
    createdAt: new Date().toISOString(),
    ...extra,
  }

  db.transactions.unshift(txn) // newest first

  return delayed(txn)
}

