/**
 * Fund a user's wallet (admin credit).
 */
export async function mockAdminFundWallet(
  userId: string,
  amount: number,
): Promise<void> {
  const wallet = db.wallets.find((w) => w.userId === userId)
  if (!wallet) return delayedError('Wallet not found for this user.')

  if (amount <= 0) return delayedError('Amount must be greater than zero.')

  wallet.balance += amount

  // Record the funding transaction
  const txn: Transaction = {
    id: uid('txn'),
    userId,
    reference: txnRef('ADM-FND'),
    type: 'Credit',
    service: 'Funding',
    amount,
    status: 'Success',
    createdAt: new Date().toISOString(),
  }
  db.transactions.unshift(txn)

  return delayed(undefined)
}

/**
 * Debit a user's wallet (admin debit with reason).
 */
export async function mockAdminDebitWallet(
  userId: string,
  amount: number,
  reason: string,
): Promise<void> {
  const wallet = db.wallets.find((w) => w.userId === userId)
  if (!wallet) return delayedError('Wallet not found for this user.')

  if (amount <= 0) return delayedError('Amount must be greater than zero.')
  if (wallet.balance < amount) {
    return delayedError(
      `Cannot debit ₦${amount.toLocaleString()}. User balance is ₦${wallet.balance.toLocaleString()}.`,
    )
  }

  wallet.balance -= amount

  // Record the debit transaction with reason in planName for audit trail
  const txn: Transaction = {
    id: uid('txn'),
    userId,
    reference: txnRef('ADM-DEB'),
    type: 'Debit',
    service: 'Funding',
    amount,
    status: 'Success',
    createdAt: new Date().toISOString(),
    planName: `Admin debit: ${reason}`,
  }
  db.transactions.unshift(txn)

  return delayed(undefined)
}

