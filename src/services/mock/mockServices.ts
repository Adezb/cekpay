/**
 * Fetch Admin Dashboard statistics.
 */
export async function mockAdminGetDashboard() {
  const usersCount = db.users.length
  const transactionsCount = db.transactions.length
  
  // Calculate revenue for today
  const today = new Date().toISOString().slice(0, 10)
  const revenueToday = db.transactions
    .filter(t => t.status === 'Success' && t.createdAt.startsWith(today))
    .reduce((sum, t) => sum + t.amount, 0)
    
  const activeAnnouncementsCount = db.announcements.filter(a => a.isActive).length
  
  // Get recent 20 transactions
  const recentTransactions = [...db.transactions]
    .sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime())
    .slice(0, 20)

  return delayed({
    usersCount,
    transactionsCount,
    revenueToday,
    activeAnnouncementsCount,
    recentTransactions
  })
}

