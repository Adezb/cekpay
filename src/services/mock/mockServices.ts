// ─── Configuration ────────────────────────────────────────

/** Simulated network latency range (ms). */
const MIN_DELAY = 1500
const MAX_DELAY = 3000

/** Probability a transaction service call "fails" (0.0 – 1.0). */
const FAILURE_RATE = 0.10

/** Maximum smart contacts per user (Director Decision #5). */
const MAX_SMART_CONTACTS = 10

// ─── In-Memory Database ───────────────────────────────────

/**
 * Mutable clone of all seed data. Functions mutate this directly.
 * Resets on page refresh (intentional for Phase 1 mock).
 */
