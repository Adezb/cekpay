/**
 * Add a new smart contact for the user.
 * Rejects if the user already has MAX_SMART_CONTACTS (Director Decision #5: max 10).
 */
export async function mockAddSmartContact(
  contact: Omit<SmartContact, 'id'>,
): Promise<SmartContact> {
  const userContacts = db.smartContacts.filter((sc) => sc.userId === contact.userId)
  if (userContacts.length >= MAX_SMART_CONTACTS) {
    return delayedError(
      `You can save a maximum of ${MAX_SMART_CONTACTS} smart contacts. Please delete one to add a new one.`,
    )
  }

  const newContact: SmartContact = {
    id: uid('sc'),
    ...contact,
  }

  db.smartContacts.push(newContact)
  return delayed(newContact)
}

/**
 * Delete a smart contact by ID.
 */
export async function mockDeleteSmartContact(contactId: string): Promise<void> {
  const index = db.smartContacts.findIndex((sc) => sc.id === contactId)
  if (index === -1) return delayedError('Contact not found.')

  db.smartContacts.splice(index, 1)
  return delayed(undefined)
}

/**
 * Update fields on an existing smart contact.
 */
export async function mockUpdateSmartContact(
  contactId: string,
  updates: Partial<SmartContact>,
): Promise<SmartContact> {
  const contact = db.smartContacts.find((sc) => sc.id === contactId)
  if (!contact) return delayedError('Contact not found.')

  Object.assign(contact, updates)
  return delayed(contact)
}

