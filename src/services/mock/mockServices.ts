/**
 * Register a new user.
 * Returns the created User (without wallet — wallet is created in `mockCreatePin`).
 */
export async function mockSignup(data: SignupRequest): Promise<User> {
  // Check for duplicate phone
  const existing = db.users.find((u) => u.phone === data.phone)
  if (existing) {
    return delayedError('An account with this phone number already exists.')
  }

  const newUser: User = {
    id: uid('usr'),
    phone: data.phone,
    firstName: data.firstName,
    lastName: data.lastName,
    pinHash: '',          // Will be set in mockCreatePin
    role: 'user',
    isBanned: false,
  }

  db.users.push(newUser)
  return delayed(newUser)
}

/**
 * Generate and "send" a 6-char alphanumeric Pass.
 *
 * In production: BulkSMSNigeria delivers "Your CEKPay Pass is A7X9TP".
 * For mock: returns the pass directly so the dev can see it in console/UI.
 */
export async function mockSendPass(phone: string): Promise<{ pass: string }> {
  const pass = generateAlphanumericPass()
  db.pendingPasses.set(phone, pass)

  // Log for dev convenience
  console.info(`[CEKPay Mock] Pass for ${phone}: ${pass}`)

  return delayed({ pass })
}

/**
 * Validate the alphanumeric pass against the one generated by `mockSendPass`.
 */
export async function mockVerifyPass(phone: string, pass: string): Promise<boolean> {
  const stored = db.pendingPasses.get(phone)
  if (!stored) {
    return delayedError('No pass was sent to this number. Please request a new one.')
  }

  const isValid = stored.toUpperCase() === pass.toUpperCase()
  if (isValid) {
    db.pendingPasses.delete(phone) // One-time use
  }

  return delayed(isValid)
}

/**
 * Create the user's 4-digit PIN and provision their wallet.
 * Returns the wallet with DVA (Dedicated Virtual Account) details.
 */
export async function mockCreatePin(userId: string, pin: string): Promise<Wallet> {
  const user = db.users.find((u) => u.id === userId)
  if (!user) return delayedError('User not found.')

  if (pin.length !== 4 || !/^\d{4}$/.test(pin)) {
    return delayedError('PIN must be exactly 4 digits.')
  }

  // Store PIN (plaintext for mock; hashed in production)
  user.pinHash = pin

  // Provision wallet with DVA
  const wallet: Wallet = {
    id: uid('wal'),
    userId,
    balance: 0,
    paystackCustomerCode: `CUS_mock_${Math.random().toString(36).slice(2, 8)}`,
    accountNumber: user.phone.replace(/^0/, ''),   // Strip leading 0 for 10-digit DVA
    bankName: 'Wema Bank',
  }

  db.wallets.push(wallet)
  return delayed(wallet)
}

/**
 * Verify a user's 4-digit PIN.
 * Used by the App Lock screen AND transaction confirmation.
 */
export async function mockVerifyPin(userId: string, pin: string): Promise<boolean> {
  const user = db.users.find((u) => u.id === userId)
  if (!user) return delayedError('User not found.')

  return delayed(user.pinHash === pin)
}

/**
 * Log in an existing user by phone and PIN.
 * Returns the User object if successful.
 */
export async function mockLogin(phone: string, pin: string): Promise<User> {
  const user = db.users.find((u) => u.phone === phone)
  if (!user) {
    return delayedError('Invalid phone number or PIN.')
  }

  if (user.pinHash !== pin) {
    return delayedError('Invalid phone number or PIN.')
  }

  if (user.isBanned) {
    return delayedError('This account has been suspended. Please contact support.')
  }

  return delayed(user)
}

